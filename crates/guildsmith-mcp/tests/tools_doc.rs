//! T114: `docs/tools.md` lists every tool of every group exactly as `tools/list` defines it
//! (annotations, description, inputs) with the permissions preflight checks. The tables between
//! the `tools:start`/`tools:end` markers are generated: run with `UPDATE_TOOLS_DOC=1` to rewrite
//! them after changing a tool.

mod common;

use std::fmt::Write as _;

use common::connect;
use guildsmith_app::fake::fixtures;
use guildsmith_app::policy::Policy;
use guildsmith_app::preflight::tool_needs;
use guildsmith_app::toolsets::Toolset;
use rmcp::model::Tool;

const START: &str = "<!-- tools:start (generated by crates/guildsmith-mcp/tests/tools_doc.rs) -->";
const END: &str = "<!-- tools:end -->";

fn ann(t: &Tool) -> String {
    let a = t.annotations.as_ref();
    let flag = |f: Option<bool>| f == Some(true);
    let mut out = vec![if flag(a.and_then(|a| a.read_only_hint)) {
        "RO"
    } else if flag(a.and_then(|a| a.destructive_hint)) {
        "D"
    } else {
        "W"
    }];
    if flag(a.and_then(|a| a.idempotent_hint)) {
        out.push("I");
    }
    if t.meta.as_ref().is_some_and(|m| m.0.contains_key("anthropic/requiresUserInteraction")) {
        out.push("asks");
    }
    out.join(", ")
}

fn title(name: &str) -> String {
    name.split('_')
        .map(|w| {
            let mut c = w.chars();
            c.next().map_or_else(String::new, |f| f.to_uppercase().chain(c).collect())
        })
        .collect::<Vec<_>>()
        .join(" ")
}

fn needs(tool: &str) -> String {
    match tool_needs(tool) {
        Some([]) | None => "—".to_owned(),
        Some(list) => list.iter().map(|p| title(p.name())).collect::<Vec<_>>().join(", "),
    }
}

fn inputs(t: &Tool) -> String {
    let schema = &t.input_schema;
    let required: Vec<&str> = schema
        .get("required")
        .and_then(|r| r.as_array())
        .map(|r| r.iter().filter_map(|v| v.as_str()).collect())
        .unwrap_or_default();
    let mut names: Vec<&String> =
        schema.get("properties").and_then(|p| p.as_object()).map(|p| p.keys().collect()).unwrap_or_default();
    names.sort();
    if names.is_empty() {
        return "—".to_owned();
    }
    names
        .iter()
        .map(|n| if required.contains(&n.as_str()) { format!("**`{n}`**") } else { format!("`{n}`") })
        .collect::<Vec<_>>()
        .join(", ")
}

async fn render() -> String {
    let app = common::app(fixtures::lab_fake(), Toolset::ALL, Policy::default());
    let c = connect(app).await;
    let tools = c.list_all_tools().await.unwrap();
    let mut out = String::new();
    for group in Toolset::ALL {
        let mut mine: Vec<&Tool> = tools.iter().filter(|t| group.tools().contains(&t.name.as_ref())).collect();
        mine.sort_by(|a, b| a.name.cmp(&b.name));
        let how = if *group == Toolset::Core {
            "default".to_owned()
        } else {
            format!("opt-in: `GUILDSMITH_TOOLSETS=core,{}`", group.name())
        };
        let count = if mine.len() == 1 { "1 tool".to_owned() } else { format!("{} tools", mine.len()) };
        let _ = writeln!(out, "## `{}` group ({how}, {count})\n", group.name());
        let _ = writeln!(out, "{}", group.purpose());
        if !group.required_intents().is_empty() {
            let _ = writeln!(out, "Needs the {} intent(s).", group.required_intents().join(", "));
        }
        out.push_str(
            "\n| Tool | Ann. | Bot needs | What it does | Inputs (required in **bold**) |\n|---|---|---|---|---|\n",
        );
        for t in mine {
            let desc = t.description.as_deref().unwrap_or_default().replace('|', "\\|");
            let _ = writeln!(out, "| `{}` | {} | {} | {desc} | {} |", t.name, ann(t), needs(&t.name), inputs(t));
        }
        out.push('\n');
    }
    out
}

#[tokio::test]
async fn tools_doc_matches_tools_list() {
    let path = format!("{}/../../docs/tools.md", env!("CARGO_MANIFEST_DIR"));
    let doc = std::fs::read_to_string(&path).unwrap();
    let (Some(a), Some(b)) = (doc.find(START), doc.find(END)) else {
        panic!("docs/tools.md needs the {START} and {END} markers");
    };
    let generated = render().await;
    let current = &doc[a + START.len()..b];
    let want = format!("\n\n{generated}");
    if current != want {
        if std::env::var("UPDATE_TOOLS_DOC").as_deref() == Ok("1") {
            let new = format!("{}{START}{want}{}", &doc[..a], &doc[b..]);
            std::fs::write(&path, new).unwrap();
        } else {
            panic!(
                "docs/tools.md is out of date; run UPDATE_TOOLS_DOC=1 cargo test -p guildsmith-mcp --test tools_doc"
            );
        }
    }
}
